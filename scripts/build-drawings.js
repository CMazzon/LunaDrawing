#!/usr/bin/env node
/**
 * Turns every SVG in /drawings into src/drawings/generated.ts.
 *
 *   npm run drawings
 *
 * SVG rules (see README "Adding a drawing"):
 *  - needs a viewBox
 *  - supported shapes: path, circle, ellipse, rect, polygon, polyline, line
 *  - every shape gets a black outline
 *  - shapes with fill="none" are just lines; all others can be tapped to fill
 *  - later shapes sit on top of earlier ones (normal SVG order)
 *  - no transform attributes (flatten them in your editor first)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'drawings');
const OUT_FILE = path.join(ROOT, 'src', 'drawings', 'generated.ts');

const SHAPES = ['path', 'circle', 'ellipse', 'rect', 'polygon', 'polyline', 'line'];
const DEFAULT_STROKE_WIDTH = 8;

function parseAttrs(text) {
  const attrs = {};
  const re = /([\w:-]+)\s*=\s*("([^"]*)"|'([^']*)')/g;
  let m;
  while ((m = re.exec(text))) attrs[m[1]] = m[3] !== undefined ? m[3] : m[4];
  // style="fill:none;stroke-width:4" wins over plain attributes, like in browsers
  if (attrs.style) {
    for (const decl of attrs.style.split(';')) {
      const [k, v] = decl.split(':').map((s) => s && s.trim());
      if (k && v) attrs[k] = v;
    }
  }
  return attrs;
}

const num = (v, fallback = 0) => (v === undefined ? fallback : parseFloat(v));
const fmt = (n) => String(Math.round(n * 100) / 100);

function ellipseD(cx, cy, rx, ry) {
  return (
    `M${fmt(cx - rx)} ${fmt(cy)} ` +
    `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx + rx)} ${fmt(cy)} ` +
    `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(cx - rx)} ${fmt(cy)} Z`
  );
}

function rectD(x, y, w, h, rx, ry) {
  if (!rx && !ry) return `M${fmt(x)} ${fmt(y)} H${fmt(x + w)} V${fmt(y + h)} H${fmt(x)} Z`;
  rx = Math.min(rx || ry, w / 2);
  ry = Math.min(ry || rx, h / 2);
  const a = (ex, ey) => `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(ex)} ${fmt(ey)}`;
  return [
    `M${fmt(x + rx)} ${fmt(y)}`,
    `H${fmt(x + w - rx)}`, a(x + w, y + ry),
    `V${fmt(y + h - ry)}`, a(x + w - rx, y + h),
    `H${fmt(x + rx)}`, a(x, y + h - ry),
    `V${fmt(y + ry)}`, a(x + rx, y),
    'Z',
  ].join(' ');
}

function pointsD(points, close) {
  const nums = points.trim().split(/[\s,]+/).map(Number);
  const parts = [];
  for (let i = 0; i + 1 < nums.length; i += 2) {
    parts.push(`${i === 0 ? 'M' : 'L'}${fmt(nums[i])} ${fmt(nums[i + 1])}`);
  }
  return parts.join(' ') + (close ? ' Z' : '');
}

function shapeToD(tag, a) {
  switch (tag) {
    case 'path':
      return a.d.replace(/\s+/g, ' ').trim();
    case 'circle':
      return ellipseD(num(a.cx), num(a.cy), num(a.r), num(a.r));
    case 'ellipse':
      return ellipseD(num(a.cx), num(a.cy), num(a.rx), num(a.ry));
    case 'rect':
      return rectD(num(a.x), num(a.y), num(a.width), num(a.height), num(a.rx), num(a.ry));
    case 'polygon':
      return pointsD(a.points, true);
    case 'polyline':
      return pointsD(a.points, false);
    case 'line':
      return `M${fmt(num(a.x1))} ${fmt(num(a.y1))} L${fmt(num(a.x2))} ${fmt(num(a.y2))}`;
  }
  throw new Error(`Unsupported shape <${tag}>`);
}

function convertSvg(svgText, fileName) {
  const id = path.basename(fileName, '.svg');
  const svgTag = svgText.match(/<svg\b([^>]*)>/);
  if (!svgTag) throw new Error(`${fileName}: no <svg> tag`);
  const root = parseAttrs(svgTag[1]);
  if (!root.viewBox) throw new Error(`${fileName}: the <svg> needs a viewBox`);
  const viewBox = root.viewBox.trim().split(/[\s,]+/).map(Number);
  const rootStroke = num(root['stroke-width'], DEFAULT_STROKE_WIDTH);
  const title = (svgText.match(/<title>([^<]*)<\/title>/) || [])[1];

  const shapes = [];
  const re = new RegExp(`<(${SHAPES.join('|')})\\b([^>]*?)\\/?>`, 'g');
  let m;
  while ((m = re.exec(svgText))) {
    const [, tag, attrText] = m;
    const a = parseAttrs(attrText);
    if (a.transform) {
      throw new Error(`${fileName}: <${tag}> has a transform. Flatten transforms in your editor first.`);
    }
    const lineOnly = a.fill === 'none' || tag === 'line' || tag === 'polyline';
    const shape = { d: shapeToD(tag, a), fillable: !lineOnly };
    const sw = num(a['stroke-width'], rootStroke);
    if (sw !== DEFAULT_STROKE_WIDTH) shape.strokeWidth = sw;
    shapes.push(shape);
  }
  if (shapes.length === 0) throw new Error(`${fileName}: no shapes found`);

  return {
    id,
    name: title ? title.trim() : id,
    viewBox,
    shapes,
  };
}

function buildAll() {
  const files = fs.readdirSync(SRC_DIR).filter((f) => f.endsWith('.svg')).sort();
  return files.map((f) => convertSvg(fs.readFileSync(path.join(SRC_DIR, f), 'utf8'), f));
}

function render(drawings) {
  return (
    '// AUTO-GENERATED by scripts/build-drawings.js from the SVGs in /drawings.\n' +
    '// Do not edit by hand: add or change an SVG and run `npm run drawings`.\n' +
    "import type { Drawing } from './types';\n\n" +
    `export const drawings: Drawing[] = ${JSON.stringify(drawings, null, 2)};\n`
  );
}

module.exports = { convertSvg, buildAll, render, OUT_FILE };

if (require.main === module) {
  const drawings = buildAll();
  fs.writeFileSync(OUT_FILE, render(drawings));
  console.log(`Wrote ${drawings.length} drawings to ${path.relative(ROOT, OUT_FILE)}`);
}
